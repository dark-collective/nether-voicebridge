    fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) {
        let Ok(entries) = std::fs::read_dir(dir) else { return };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                collect_files(&path, out);
            } else {
                out.push(path);
            }
        }
    }

    /// #72 F6-2 regression: the real `config.toml` (with live appservice +
    /// puppet tokens) must never land under the scenario's artifacts tree —
    /// only a redacted copy may. `/bin/cat` stands in for the bridge binary
    /// (reads empty stdin, exits 0 immediately) so no real bridge is needed.
    #[tokio::test]
    async fn secrets_never_land_under_the_artifacts_workdir() {
        let mut cfg = cfg();
        cfg.bridge_bin = "/bin/cat".into();
        // Quote-free token: `cfg()`'s default contains a `"`, which TOML-escapes
        // to `\"` on disk — a raw-substring search would then miss it, failing
        // the sanity check here and making the artifact leak scan below vacuous.
        cfg.appservice_token = "sekrit-as-token-plain".into();
        let artifacts_root =
            std::env::temp_dir().join(format!("nvb-e2e-artifacts-test-{}", std::process::id()));
        let workdir = artifacts_root.join("bridge");
        tokio::fs::create_dir_all(&workdir).await.unwrap();

        let bridge = BridgeUnderTest::start(&cfg, Profile::Compressed, "", &workdir)
            .await
            .expect("stub bridge starts");

        // Sanity: the real secret config really was written somewhere
        // outside the artifacts tree — otherwise the assertions below would
        // pass vacuously.
        let real_config = std::fs::read_to_string(bridge.secrets_dir.join("config.toml"))
            .expect("real config.toml exists in the secrets dir");
        assert!(
            real_config.contains(cfg.appservice_token.as_str()),
            "sanity: secrets dir holds the real token"
        );
        assert!(
            !bridge.secrets_dir.starts_with(&artifacts_root),
            "secrets dir must live outside the artifacts tree"
        );

        bridge.kill().await;

        let mut files = Vec::new();
        collect_files(&artifacts_root, &mut files);
        assert!(!files.is_empty(), "expected at least the redacted config + log under artifacts");
        for f in &files {
            let content = std::fs::read_to_string(f).unwrap_or_default();
            assert!(
                !content.contains(cfg.appservice_token.as_str()),
                "appservice token leaked into artifact {f:?}"
            );
            for tok in &cfg.puppet_tokens {
                assert!(!content.contains(tok.as_str()), "puppet token leaked into artifact {f:?}");
            }
        }

        std::fs::remove_dir_all(&artifacts_root).ok();
    }
