//! BridgeUnderTest: the REAL `nether-voicebridge` binary as a child process.
//!
//! Running the shipped binary (not a test harness linking bridge code)
//! exercises `main.rs` boot, tenants loading, SIGHUP reconcile, SIGTERM drain
//! and panic containment exactly as production does. Its JSON stdout
//! (`NVB_LOG_JSON=1`) feeds a [`LogScraper`]; the raw stream is also persisted
//! to the scenario's artifacts dir.
//!
//! Each instance gets a private workdir: a generated `config.toml`
//! (`[server.test]` + the harness `[puppets]` pool — no static bridges) and a
//! `data/` NVB_DATA_DIR holding `tenants.toml` (all bridges are tenants, so
//! scenarios drive the production reconcile path via
//! [`BridgeUnderTest::reconfigure_tenants`]).

use crate::config::{E2eConfig, Profile};
use crate::logscrape::LogScraper;
use anyhow::{Context, Result, bail};
use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::Arc;
use std::time::Duration;
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio::process::{Child, Command};

/// Render the bridge-under-test `config.toml`: one `[server.test]` profile
/// (tenants reference it as `server = "test"`) plus the harness puppet pool.
/// No `[[bridge]]` blocks and no `[timing]` — compressed timing rides the
/// `NVB_TIMING` env preset so the C1 env path is exercised too.
pub fn generate_config(cfg: &E2eConfig) -> String {
    render_config(cfg, &cfg.puppet_tokens, false, "")
}

/// [`generate_config`] plus the `[management]` + `[limits]` blocks that turn on
/// the self-serve `link`/approval path (#76). Opt-in per scenario — it starts a
/// second Client (the management bot) and registers the `/bridge` slash command
/// on puppet 0, neither of which the audio/smoke scenarios want — so the
/// #76 scenario uses [`BridgeUnderTest::start_with_management`] and everything
/// else stays byte-identical.
/// `extra_limits` (#99) appends raw `[limits]` lines so the invite-lifecycle
/// scenarios can arm knobs the standing block leaves unset on purpose —
/// `mgmt_cooldown_secs` foremost, whose absence is exactly why the suite
/// never reproduced #97. Empty for everyone else.
pub fn generate_config_with_management(cfg: &E2eConfig, extra_limits: &str) -> String {
    render_config(cfg, &cfg.puppet_tokens, true, extra_limits)
}

/// [`generate_config`] with the puppet pool restricted to the first `pool_size`
/// tokens — the #7 `overflow_fcfs_promotion` scenario forces a deterministic
/// 1-bot pool so overflow happens regardless of how many tokens the shared
/// `NVB_E2E_PUPPET_TOKENS` secret holds. `pool_size` is clamped to the available
/// tokens (and to ≥1, since the config loader rejects an empty pool).
pub fn generate_config_with_pool_size(cfg: &E2eConfig, pool_size: usize) -> String {
    let n = pool_size.clamp(1, cfg.puppet_tokens.len());
    render_config(cfg, &cfg.puppet_tokens[..n], false, "")
}

fn render_config(
    cfg: &E2eConfig,
    puppet_tokens: &[String],
    management: bool,
    extra_limits: &str,
) -> String {
    let mut out = String::new();
    out.push_str("# Generated by nvb-e2e — bridge-under-test configuration.\n\n");
    out.push_str("[server.test]\n");
    out.push_str(&format!("homeserver_url = {}\n", toml_str(&cfg.homeserver_url)));
    if let Some(d) = &cfg.matrix_domain {
        out.push_str(&format!("matrix_domain = {}\n", toml_str(d)));
    }
    out.push_str(&format!("sender_localpart = {}\n", toml_str(&cfg.sender_localpart)));
    out.push_str(&format!("appservice_id = {}\n", toml_str(&cfg.appservice_id)));
    out.push_str(&format!("appservice_token = {}\n", toml_str(&cfg.appservice_token)));
    out.push_str("\n[puppets]\ntokens = [\n");
    for t in puppet_tokens {
        out.push_str(&format!("    {},\n", toml_str(t)));
    }
    out.push_str("]\n");
    if management {
        out.push_str(&management_and_limits_block(cfg, extra_limits));
    }
    out
}

/// The `[limits]` + `[management]` blocks (secret-free, so identical in the
/// redacted rendering). All three auth knobs are ON — the config loader rejects
/// `open_registration` without both `require_*` knobs — so the #76 self-serve
/// scenario exercises the whole gated path. The `allow` operator is a
/// placeholder MXID that never acts (the scenario drives a non-allowlisted
/// self-serve user); its only role is satisfying the non-empty-allowlist
/// validation. The management bot's `bot_user_id` is auto-derived from the
/// profile's `sender_localpart` (`{localpart}_bot`), exactly as bridges derive
/// theirs — nothing extra to state. `approval_bot_index = 0` registers the
/// `/bridge approve` slash command on puppet 0 — a harmless, idempotent side
/// effect; the `link → pending-code` path itself needs no Discord round-trip.
fn management_and_limits_block(cfg: &E2eConfig, extra_limits: &str) -> String {
    let mut out = String::new();
    out.push_str("\n[limits]\n");
    // Small per-owner cap so the scenario can exercise the ceiling (a pending
    // link counts toward it). mgmt_cooldown_secs is left unset (unlimited) so
    // the multi-command run is never single-shot rate-gated — scenarios that
    // need it armed (#99's invite lifecycle) pass it via `extra_limits`.
    out.push_str("max_tenants_per_owner = 1\n");
    // #77 anti-Sybil knobs. Per-guild cap 2 = the seeded foreign tenant (1) plus
    // one self-serve pending link fills the guild, so a THIRD owner's link to it
    // is refused — the scenario exercises exactly that ceiling. Link-attempt
    // budget 3 = a fresh user's 4th probe-reaching `link` within the window is
    // velocity-refused (the window defaults to 1 h, and the gate state is
    // in-memory so it resets with the fresh bridge process each run).
    out.push_str("max_tenants_per_guild = 2\n");
    out.push_str("max_link_attempts = 3\n");
    // #84 global (cross-MXID) budget — mandatory under open_registration. Set
    // generously so the scenario's handful of link attempts never trip it (it
    // exists to bound a Sybil swarm, not the normal flow); the gate state is
    // in-memory so it resets with the fresh bridge process each run.
    out.push_str("max_global_link_attempts = 100\n");
    // #99 scenario-specific `[limits]` lines (raw TOML, e.g. "mgmt_cooldown_secs
    // = 60\n"). Secret-free by construction — callers pass literals.
    out.push_str(extra_limits);
    out.push_str("\n[management]\n");
    out.push_str("server = \"test\"\n");
    out.push_str(&format!(
        "allow = [{}]\n",
        toml_str(&format!("@nvbtest_operator:{}", cfg.server_domain()))
    ));
    out.push_str("require_room_authority = true\n");
    out.push_str("require_discord_approval = true\n");
    out.push_str("open_registration = true\n");
    out.push_str("approval_timeout_secs = 300\n");
    out.push_str("approval_bot_index = 0\n");
    // #92 docs_url: exercised live (appended to greeting/help/pending replies);
    // the scenario's substring asserts all match mid-string, so appending is
    // invisible to them.
    out.push_str("docs_url = \"https://nether.wiki/matrix/voice-bridge/\"\n");
    // #94 instance_notice: appended to greeting/help after the guide line —
    // same append-only safety argument as docs_url.
    out.push_str("instance_notice = \"Open beta — test notice.\"\n");
    out
}

/// One `[[bridge]]` tenants.toml entry (tenants must carry an explicit name).
pub fn tenant_entry(name: &str, room_id: &str, guild_id: &str, channel_id: &str) -> String {
    tenant_entry_opts(name, room_id, guild_id, channel_id, false)
}

/// [`tenant_entry`] with the `capture_wav` diagnostic taps switched on: the
/// bridge writes Tap A (`capture_<ssrc>.wav`, Discord ingress) and Tap B
/// (`publish_<key>.wav`, the mono PCM handed to LiveKit) into its cwd — which
/// [`BridgeUnderTest::start`] pins to the scenario workdir, so the taps become
/// artifacts. The `audio_d2m_enc` scenario oracles Tap B (its Matrix-side
/// decrypting listener is deferred).
pub fn tenant_entry_opts(
    name: &str,
    room_id: &str,
    guild_id: &str,
    channel_id: &str,
    capture_wav: bool,
) -> String {
    format!(
        "[[bridge]]\nname = {}\nserver = \"test\"\nroom_id = {}\n\n[bridge.discord]\nguild_id = {}\nchannel_id = {}\ncapture_wav = {}\n\n",
        toml_str(name),
        toml_str(room_id),
        toml_str(guild_id),
        toml_str(channel_id),
        capture_wav,
    )
}

fn toml_str(s: &str) -> String {
    // Basic TOML string quoting; the values here (urls, ids, tokens) never
    // contain control characters.
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Same shape as [`generate_config`], with every secret replaced by a fixed
/// placeholder — this redacted rendering is what may safely be persisted
/// under the scenario's artifacts tree for debuggability (#72 F6-2). The real
/// config (with the live appservice + puppet tokens) is written to a
/// non-artifact location instead — see [`BridgeUnderTest::start`]. `management`
/// mirrors the real config's opt-in `[management]`/`[limits]` (secret-free).
fn generate_config_redacted(
    cfg: &E2eConfig,
    pool_size: usize,
    management: bool,
    extra_limits: &str,
) -> String {
    let mut out = String::new();
    out.push_str(
        "# Generated by nvb-e2e — bridge-under-test configuration (REDACTED).\n\
         # The real config.toml (with live tokens) is written outside the\n\
         # artifacts tree; see BridgeUnderTest::start.\n\n",
    );
    out.push_str("[server.test]\n");
    out.push_str(&format!("homeserver_url = {}\n", toml_str(&cfg.homeserver_url)));
    if let Some(d) = &cfg.matrix_domain {
        out.push_str(&format!("matrix_domain = {}\n", toml_str(d)));
    }
    out.push_str(&format!("sender_localpart = {}\n", toml_str(&cfg.sender_localpart)));
    out.push_str(&format!("appservice_id = {}\n", toml_str(&cfg.appservice_id)));
    out.push_str("appservice_token = \"REDACTED\"\n");
    out.push_str("\n[puppets]\ntokens = [\n");
    let n = pool_size.clamp(1, cfg.puppet_tokens.len());
    for _ in 0..n {
        out.push_str("    \"REDACTED\",\n");
    }
    out.push_str("]\n");
    if management {
        // Secret-free — identical to the real rendering.
        out.push_str(&management_and_limits_block(cfg, extra_limits));
    }
    out
}

/// A location outside any scenario's artifacts tree to hold the real
/// generated `config.toml` (secrets — never collected/uploaded). Keyed off
/// the (unique per scenario) workdir path plus the harness pid so concurrent
/// or repeated runs never collide.
fn secrets_dir_for(workdir: &Path) -> PathBuf {
    let mut hasher = DefaultHasher::new();
    workdir.hash(&mut hasher);
    std::process::id().hash(&mut hasher);
    std::env::temp_dir().join(format!("nvb-e2e-secrets-{:x}", hasher.finish()))
}

pub struct BridgeUnderTest {
    child: Child,
    pid: i32,
    pub scraper: Arc<LogScraper>,
    // Scenario surface built ahead of its first caller (the D2/D3 reconcile
    // and artifact-inspection scenarios) — see the design doc's D1 spec.
    #[allow(dead_code)]
    pub workdir: PathBuf,
    tenants_path: PathBuf,
    /// Holds the real `config.toml` (secrets) — outside the artifacts tree;
    /// removed best-effort on every teardown path (#72 F6-2).
    secrets_dir: PathBuf,
}

impl BridgeUnderTest {
    /// Spawn the bridge with the given initial tenants body under
    /// `workdir` (created fresh; typically `<artifacts>/<scenario>/bridge`).
    pub async fn start(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
    ) -> Result<Self> {
        Self::start_inner(cfg, profile, tenants_toml, workdir, false, None, &[], "").await
    }

    /// Like [`start`](Self::start) but with the `[management]` self-serve stack
    /// enabled (#76): the bridge-under-test also runs the Matrix management bot
    /// (all three auth knobs ON) and registers the `/bridge` command on puppet
    /// 0. Only the `mgmt_self_serve_link` scenario wants this — every other
    /// scenario's config stays byte-identical via [`start`](Self::start).
    pub async fn start_with_management(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
    ) -> Result<Self> {
        Self::start_inner(cfg, profile, tenants_toml, workdir, true, None, &[], "").await
    }

    /// Like [`start_with_management`](Self::start_with_management) with extra
    /// env vars for the bridge child (#95's `room_misconfig_notice` compresses
    /// the maintenance sweep via `NVB_MAINTENANCE_INTERVAL_SECS`).
    pub async fn start_with_management_env(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
        extra_env: &[(&str, &str)],
    ) -> Result<Self> {
        Self::start_inner(cfg, profile, tenants_toml, workdir, true, None, extra_env, "").await
    }

    /// Like [`start_with_management_env`](Self::start_with_management_env) plus
    /// extra raw `[limits]` lines (#99): the invite-lifecycle scenarios arm
    /// `mgmt_cooldown_secs` — deliberately unset in the standing block, which
    /// is exactly why the suite never reproduced #97's cooldown-decline.
    pub async fn start_with_management_opts(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
        extra_env: &[(&str, &str)],
        extra_limits: &str,
    ) -> Result<Self> {
        Self::start_inner(cfg, profile, tenants_toml, workdir, true, None, extra_env, extra_limits)
            .await
    }

    /// Like [`start`](Self::start) but with the puppet pool restricted to the
    /// first `pool_size` tokens (#7 `overflow_fcfs_promotion` forces a 1-bot
    /// pool so overflow is deterministic). See [`generate_config_with_pool_size`].
    pub async fn start_with_pool_size(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
        pool_size: usize,
    ) -> Result<Self> {
        Self::start_inner(cfg, profile, tenants_toml, workdir, false, Some(pool_size), &[], "")
            .await
    }

    #[allow(clippy::too_many_arguments)]
    async fn start_inner(
        cfg: &E2eConfig,
        profile: Profile,
        tenants_toml: &str,
        workdir: &Path,
        management: bool,
        pool_size: Option<usize>,
        extra_env: &[(&str, &str)],
        extra_limits: &str,
    ) -> Result<Self> {
        let data_dir = workdir.join("data");
        tokio::fs::create_dir_all(&data_dir).await.context("creating bridge workdir")?;
        // The child runs with `workdir` as cwd, so every path handed to it
        // (CONFIG_PATH, NVB_DATA_DIR) must be absolute — an artifacts dir
        // given relative to the HARNESS cwd would otherwise dangle.
        let workdir = &tokio::fs::canonicalize(workdir).await.context("resolving bridge workdir")?;
        let data_dir = workdir.join("data");
        // The real config.toml carries the plaintext appservice token and
        // every puppet bot token — it must never land under the artifacts
        // tree (config.rs's own invariant: secrets are "never echoed into
        // artifacts"). Write it to a private, non-collectable location and
        // leave only a redacted copy under `workdir` for debuggability
        // (#72 F6-2).
        let secrets_dir = secrets_dir_for(workdir);
        tokio::fs::create_dir_all(&secrets_dir).await.context("creating bridge secrets dir")?;
        let config_path = secrets_dir.join("config.toml");
        let real_config = match (management, pool_size) {
            (true, _) => generate_config_with_management(cfg, extra_limits),
            (false, Some(n)) => generate_config_with_pool_size(cfg, n),
            (false, None) => generate_config(cfg),
        };
        tokio::fs::write(&config_path, real_config).await?;
        let redacted_pool = pool_size.unwrap_or(cfg.puppet_tokens.len());
        tokio::fs::write(
            workdir.join("config.redacted.toml"),
            generate_config_redacted(cfg, redacted_pool, management, extra_limits),
        )
        .await?;
        let tenants_path = data_dir.join("tenants.toml");
        tokio::fs::write(&tenants_path, tenants_toml).await?;

        if !cfg.bridge_bin.exists() {
            bail!("bridge binary not found at {} (set NVB_E2E_BRIDGE_BIN)", cfg.bridge_bin.display());
        }

        let mut cmd = Command::new(&cfg.bridge_bin);
        // The child's cwd is its workdir so relative diagnostic outputs (the
        // capture_wav taps) land in the scenario artifacts. `bridge_bin` is
        // canonicalized at config load, so a relative path still resolves.
        cmd.current_dir(workdir)
            .env("CONFIG_PATH", &config_path)
            .env("NVB_DATA_DIR", &data_dir)
            .env("NVB_LOG_JSON", "1")
            .env(
                "RUST_LOG",
                "nether_voicebridge=info,nvb_audio=info,nvb_discord=info,\
                 nvb_matrix_rtc=info,nvb_config=info",
            )
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true);
        match profile {
            Profile::Compressed => {
                cmd.env("NVB_TIMING", "compressed");
            }
            Profile::Real => {
                cmd.env_remove("NVB_TIMING");
            }
        }
        for (k, v) in extra_env {
            cmd.env(k, v);
        }

        let mut child = cmd.spawn().context("spawning bridge-under-test")?;
        let pid = child.id().context("bridge child has no pid")? as i32;
        let scraper = Arc::new(LogScraper::new());

        // Pump stdout (JSON events) and stderr (panics, glibc noise) into the
        // scraper AND a persistent raw log artifact.
        let log_file = tokio::fs::File::create(workdir.join("bridge.log")).await?;
        let log_file = Arc::new(tokio::sync::Mutex::new(log_file));
        let stdout = child.stdout.take().context("no stdout pipe")?;
        let stderr = child.stderr.take().context("no stderr pipe")?;
        for stream in [
            tokio::io::BufReader::new(Box::pin(stdout) as std::pin::Pin<Box<dyn tokio::io::AsyncRead + Send>>),
            BufReader::new(Box::pin(stderr) as std::pin::Pin<Box<dyn tokio::io::AsyncRead + Send>>),
        ] {
            let scraper = scraper.clone();
            let log_file = log_file.clone();
            tokio::spawn(async move {
                let mut lines = stream.lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    scraper.ingest_line(&line);
                    let mut f = log_file.lock().await;
                    let _ = f.write_all(line.as_bytes()).await;
                    let _ = f.write_all(b"\n").await;
                }
            });
        }

        Ok(Self { child, pid, scraper, workdir: workdir.to_owned(), tenants_path, secrets_dir })
    }

    /// Wait until every named bridge finished its initial Matrix sync + state
    /// scan ("initial call snapshot loaded" under that bridge's span).
    pub async fn await_ready(&self, bridges: &[&str], timeout: Duration) -> Result<()> {
        for name in bridges {
            let name = name.to_string();
            self.scraper
                .await_event(timeout, |e| {
                    e.message.contains("initial call snapshot loaded") && e.in_bridge(&name)
                })
                .await
                .with_context(|| format!("bridge '{name}' never became ready"))?;
        }
        Ok(())
    }

    /// Write `<data_dir>/banlist.toml` for the management bot's deny-list
    /// checks (#76 self-serve scenario). The bot reads the file lazily on every
    /// command, so seeding after [`start`](Self::start) still takes effect.
    #[allow(dead_code)] // first caller: the #76 mgmt_self_serve scenario
    pub async fn seed_banlist(&self, banlist_toml: &str) -> Result<()> {
        let path = self.workdir.join("data").join("banlist.toml");
        tokio::fs::write(&path, banlist_toml).await.context("seeding banlist.toml")?;
        Ok(())
    }

    /// Atomically replace `tenants.toml` and SIGHUP — the production
    /// reconcile path (temp file + rename, exactly as the runbook prescribes).
    /// First callers arrive with the D2/D3 reconcile scenarios.
    #[allow(dead_code)]
    pub async fn reconfigure_tenants(&self, tenants_toml: &str) -> Result<()> {
        let tmp = self.tenants_path.with_extension("toml.new");
        tokio::fs::write(&tmp, tenants_toml).await?;
        tokio::fs::rename(&tmp, &self.tenants_path).await?;
        self.signal(libc::SIGHUP)
    }

    #[allow(dead_code)] // D2/D3 reconcile scenarios
    pub fn sighup(&self) -> Result<()> {
        self.signal(libc::SIGHUP)
    }

    fn signal(&self, sig: i32) -> Result<()> {
        // SAFETY: plain kill(2) on the child pid we own.
        let rc = unsafe { libc::kill(self.pid, sig) };
        if rc != 0 {
            bail!("kill({}, {sig}) failed: {}", self.pid, std::io::Error::last_os_error());
        }
        Ok(())
    }

    /// SIGTERM and wait for the drain to finish — the graceful-shutdown
    /// postcondition every scenario ends with. Escalates to SIGKILL on
    /// timeout (and reports it as an error: a wedged drain IS a failure).
    pub async fn sigterm_and_wait(mut self, timeout: Duration) -> Result<()> {
        self.signal(libc::SIGTERM)?;
        let result: Result<()> = match tokio::time::timeout(timeout, self.child.wait()).await {
            Ok(status) => match status.context("waiting on bridge child") {
                Ok(status) if status.success() => Ok(()),
                Ok(status) => Err(anyhow::anyhow!("bridge exited non-zero after SIGTERM: {status}")),
                Err(e) => Err(e),
            },
            Err(_) => {
                let _ = self.child.kill().await;
                Err(anyhow::anyhow!(
                    "bridge did not drain within {timeout:?} after SIGTERM — SIGKILLed"
                ))
            }
        };
        // The child is confirmed gone (or force-killed) by this point — safe
        // to scrub the secrets dir regardless of outcome (#72 F6-2).
        let _ = tokio::fs::remove_dir_all(&self.secrets_dir).await;
        result
    }

    /// Hard-kill (scenario cleanup on failure paths). Prefer
    /// [`sigterm_and_wait`](Self::sigterm_and_wait) — SIGKILL leaves zombie
    /// Discord voice sessions behind.
    pub async fn kill(mut self) {
        let _ = self.child.kill().await;
        let _ = self.child.wait().await;
        let _ = tokio::fs::remove_dir_all(&self.secrets_dir).await;
    }
}

