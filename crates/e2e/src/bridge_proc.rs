    /// #7: the restricted-pool rendering yields exactly `pool_size` puppet
    /// tokens (clamped to what's provisioned, floored at 1) and still loads via
    /// the real `nvb-config` loader — so `overflow_fcfs_promotion` gets its
    /// deterministic 1-bot pool no matter how many tokens the secret holds.
    #[test]
    fn restricted_pool_config_loads_with_pool_size_tokens() {
        let cfg = cfg(); // two puppet tokens
        let dir =
            std::env::temp_dir().join(format!("nvb-e2e-poolcfg-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();

        // pool_size = 1 → exactly one token, even though cfg has two.
        let cfg_path = dir.join("config.toml");
        std::fs::write(&cfg_path, generate_config_with_pool_size(&cfg, 1)).unwrap();
        let loaded = nvb_config::Config::load(cfg_path.to_str().unwrap()).expect("config loads");
        assert_eq!(loaded.puppets.tokens.len(), 1, "pool restricted to 1 bot");

        // Clamp: pool_size larger than provisioned tokens caps at the count;
        // pool_size 0 floors at 1 (the loader rejects an empty pool).
        let hi_path = dir.join("hi.toml");
        std::fs::write(&hi_path, generate_config_with_pool_size(&cfg, 99)).unwrap();
        let clamp_hi = nvb_config::Config::load(hi_path.to_str().unwrap())
            .expect("clamped-high config loads");
        assert_eq!(clamp_hi.puppets.tokens.len(), 2, "clamped to provisioned count");
        let lo_path = dir.join("lo.toml");
        std::fs::write(&lo_path, generate_config_with_pool_size(&cfg, 0)).unwrap();
        let clamp_lo = nvb_config::Config::load(lo_path.to_str().unwrap())
            .expect("clamped-low config loads");
        assert_eq!(clamp_lo.puppets.tokens.len(), 1, "floored at 1 bot");

        std::fs::remove_dir_all(&dir).ok();
    }

